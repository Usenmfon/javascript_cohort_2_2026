//Loop - For, While, Do While

for(let i = 6; i <= 5; i++)
{
    console.log(i + ". Hello World!")
}
console.log("=============================")
let i = 6;
while(i <= 5)
{
    console.log(i + ". Hello World!")
    i++ // i = i + 1
}

